export function guidelineByKey(key: string): GuidelineEntry | undefined {
  return GUIDELINES.find((g) => g.key === key);
}

/** Map a detected study design to the appropriate reporting guideline. */
export function guidelineForDesign(design: string): GuidelineEntry {
  const d = (design || "").toLowerCase();
  const matches: Array<[RegExp, string]> = [
    [/rct|randomized|randomised|کارآزمایی.*تصادفی|کارازمایی تصادفی/, "consort"],
    [/systematic|meta.?analysis|مرور نظام|مرور سيستم|مرور سیستم|متاآنالیز|متا آنالیز/, "prisma"],
    [/scoping|مرور دامنه/, "prisma"],
    [/protocol|پروتکل/, "spirit"],
    [/diagnostic|دقت تشخیص/, "stard"],
    [/prediction|model|پیش.?بینی|مدل/, "tripod_ai"],
    [/qualitative|کیفی/, "coreq"],
    [/case.?report|گزارش مورد/, "care"],
    [/animal|حیوان/, "arrive"],
    [/quality.?improvement|بهبود کیفیت/, "squire"],
    [/economic|اقتصادی/, "cheers"],
    [/cohort|case.?control|cross.?sectional|observational|کوهورت|مقطعی|موردی|شاهد/, "strobe"],
  ];
  for (const [re, key] of matches) {
    if (re.test(d)) return guidelineByKey(key)!;
  }
  return guidelineByKey("strobe")!;
}
